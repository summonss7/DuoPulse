// DuoPulse — модель отображения страницы ошибки загрузки (карточка
// duopulse-048, docs/02 §6.2): чистые функции без DOM — контекст Core
// (адрес/причина) и срез статуса VPN переводятся в данные рендера: хост для
// split-правила и решение кнопки «этот сайт — через туннель» (автоповтор
// по правилу или подсказка включить туннель/split-режим).
// i18n (duopulse-137): тексты подсказок — через t(); ключ — русская
// строка-исходник, словари — src/i18n/dict-*.ts.
import { t } from "../i18n";

/** Хост упавшего адреса для split-правила «этот сайт — через туннель»:
 *  только внешние http/https, «www.» снимается (правило ловит домен и
 *  поддомены); IP-адреса не считаются — правило доменное. null — кнопки
 *  «через туннель» не будет. */
export function errorHost(url: string | undefined): string | null {
  if (!url) return null;
  let host: string;
  try {
    const u = new URL(url);
    if (u.protocol !== "http:" && u.protocol !== "https:") return null;
    host = u.hostname;
  } catch {
    return null;
  }
  host = host.toLowerCase().replace(/^www\./, "");
  if (!host || host.includes(":") || /^\d+\.\d+\.\d+\.\d+$/.test(host)) return null;
  return host;
}

/** Минимальный срез vpn.status, нужный решению кнопки. */
export interface VpnSlice {
  /** Фактический маршрут роутера: off | proxy | wg. */
  mode: string;
  /** Режим split-правил: off | global | split. */
  routing: string;
  /** Снапшот туннеля (нужно имя профиля для подсказки маршрута, duopulse-114). */
  wg?: { profileName: string } | null;
}

/** Подсказка, каким маршрутом грузился упавший сайт (duopulse-114): без неё
 *  «код 9» при живом в других браузерах сайте выглядит багом браузера, хотя
 *  весь трафик шёл через туннель/прокси и сайт отказал его адресу. null —
 *  грузился напрямую, пояснять нечего. */
export function routeContextNote(st: VpnSlice | null): string | null {
  if (!st) return null;
  if (st.mode === "wg") {
    // split: сайт шёл напрямую (правила «tunnel» для него не было) — туннель
    // ни при чём, подсказка не нужна.
    if (st.routing !== "global") return null;
    return st.wg?.profileName
      ? t("Весь трафик сейчас идёт через туннель «{p}» — сайт мог отказать соединениям с его адреса. Кнопка «напрямую» ниже откроет этот сайт в обход туннеля.", {
          p: st.wg.profileName,
        })
      : t("Весь трафик сейчас идёт через туннель — сайт мог отказать соединениям с его адреса. Кнопка «напрямую» ниже откроет этот сайт в обход туннеля.");
  }
  if (st.mode === "proxy") {
    return t("Весь трафик сейчас идёт через внешний прокси — сайт мог отказать соединениям с его адреса.");
  }
  return null;
}

/** Что делать после vpn.add_rule: туннель поднят и правило действует
 * (режим split/global) — сразу повторная загрузка по правилу; иначе —
 * подсказка: включить туннель и/или split-режим, затем «Повторить». */
export function tunnelAction(st: VpnSlice | null): { retry: boolean; note: string } {
  if (!st) {
    return {
      retry: false,
      note: t("Правило добавлено, статус туннеля неизвестен — нажмите «Повторить»."),
    };
  }
  if (st.mode !== "wg") {
    return {
      retry: false,
      note: t("Правило добавлено. Включите туннель (щит в панели VPN) и нажмите «Повторить»."),
    };
  }
  if (st.routing === "off") {
    return {
      retry: false,
      note: t("Правило добавлено, но режим выключен — включите split в панели VPN и повторите."),
    };
  }
  return { retry: true, note: t("Правило добавлено — пробуем снова через туннель…") };
}

/** Кнопка «этот сайт — напрямую» показывается только при поднятом туннеле
 *  (карточка duopulse-075): сайт уже пытались через туннель; туннель выключен
 *  — сайт и так идёт напрямую, кнопка бессмысленна. */
export function directActionAvailable(st: VpnSlice | null): boolean {
  return st?.mode === "wg";
}

/** Решение кнопки «этот сайт — напрямую» (карточка duopulse-075): показывается
 *  только при поднятом туннеле — сайт уже пытались через туннель и он не
 *  открылся (типовой случай: российские сервисы — mail.ru, Яндекс — режут
 *  зарубежные IP, и в глобальном режиме «не работают»). Правило «напрямую»
 *  действует в split; глобальный режим страница до повтора переключает на
 *  split (setMode) — остальной трафик остаётся в туннеле. */
export function directAction(st: VpnSlice | null): { retry: boolean; note: string } {
  if (!st) {
    return {
      retry: false,
      note: t("Правило добавлено, статус туннеля неизвестен — нажмите «Повторить»."),
    };
  }
  return {
    retry: true,
    note:
      st.routing === "global"
        ? t("Глобальный режим сменён на split: этот сайт — напрямую, остальное — через туннель. Пробуем снова…")
        : t("Правило «напрямую» добавлено — пробуем снова…"),
  };
}
