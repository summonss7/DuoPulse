// DuoPulse — дата сборки для внутренних страниц. Бейдж версии в навбаре
// убран (карточка duopulse-078): версия и дата сборки живут в заголовке
// окна (main.rs), возле адресной строки — только логотип и стрелки.
// Здесь остаётся форматтер даты: app.build_info отдаёт unix-момент
// компиляции (build.rs), страница «Настройки» показывает его в строке
// версии раздела «Обновления».
/** «05.11.2026» из unix-секунд; пустая строка — момент неизвестен. */
export function buildDateRu(unix: number): string {
  if (!unix) return "";
  return new Date(unix * 1000).toLocaleDateString("ru-RU");
}
